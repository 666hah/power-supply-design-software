from functools import partial

import numpy as np

from docs.derivations.illustrations import BLUE, ORANGE, TEAL, MUTED, figure


def curves(x, traces, xlabel, ylabel, *, horizontal=(), vertical=(), log=False, dots=False):
    fig = figure(7.1, 3.2)
    ax = fig.subplots()
    for (name, y), color in zip(traces, (BLUE, ORANGE, TEAL)):
        ax.plot(x, y, color=color, label=name, marker='o' if dots else None)
    for value, name in horizontal:
        ax.axhline(value, color=MUTED, ls='--', lw=1, label=name)
    for value in vertical:
        ax.axvline(value, color=MUTED, ls=':', lw=1)
    if log:
        ax.set_xscale('log')
    ax.grid(alpha=.17)
    ax.set(xlabel=xlabel, ylabel=ylabel)
    ax.legend(loc='best')
    return fig


def comparator_bars(names, values, ylabel):
    fig = figure(7.1, 3.2)
    ax = fig.subplots()
    bars = ax.bar(names, values, width=.54, color=[BLUE, TEAL, ORANGE, MUTED][:len(names)])
    ax.bar_label(bars, labels=[f'{n:.3g}' for n in values], padding=4)
    ax.set(ylabel=ylabel, ylim=(0, max(values)*1.22))
    ax.grid(axis='y', alpha=.17)
    return fig


def field_plot(key):
    if key == 'ports':
        v = np.linspace(8, 14, 181)
        return curves(v, [('24 Ω 电阻', v/24), ('已使能的 6 W 负载', 6/v)],
                      '负载端口电压 / V', '流入负载的电流 / A', vertical=(12,))
    if key == 'samples':
        return curves([0,.5,1,4], [('保持原始采样时刻的分段线性电流',[0,4,0,0])],
                      '时间 / µs','瞬时电流 / A', horizontal=[(.5,'整周期平均值')], dots=True)
    if key == 'pulses':
        d = np.linspace(.1, 1, 181)
        return curves(d, [('脉冲峰值',1/d), ('方均根值',1/np.sqrt(d)), ('平均值',np.ones_like(d))],
                      '导通时间占比', '电流 / A')
    if key == 'polarity':
        return comparator_bars(['原边开路自感¹','副边开路自感¹','串联同向','串联反向'],
                               [100,25,223,27], '电感 / µH　　¹ 另一绕组开路')
    if key == 'short':
        return comparator_bars(['二、三绕组开路','仅短绕组二','仅短绕组三','同时短两绕组'],
                               [100,7.84,100-28**2/9,196/29], '原边测得的电感 / µH')
    if key == 'mesh':
        h = np.linspace(.15,1.05,121)
        return curves(h,[('教学误差模型',4+.8*h**2)],'局部特征网格边长 h / mm',
                      '原边短路电感 / µH',horizontal=[(4,'外推截距')],vertical=(.25,.5,1.))
    if key == 'or':
        i=np.linspace(0,4,201)
        a=np.minimum(i,(.2+.1*i)/.3)
        return curves(i,[('供电支路 A',a),('供电支路 B',i-a)],'母线负载电流 / A',
                      '支路供电电流 / A',vertical=(1.,))
    if key == 'start':
        t=np.linspace(0,5,501)
        return curves(t,[('计划的总电流需求',np.where(t<4,.6,0)+np.where(t<2,.35,.65))],
                      '软启动开始后的时间 / ms','总需求电流 / A',
                      horizontal=[(1.1,'上游连续限流阈值')],vertical=(2,4))
    if key == 'ldo':
        v=np.linspace(3.65,6.5,171)
        return curves(v,[('0.30 A 负载',55+85*((v-3.3)*.3+v*50e-6)),
                         ('0.15 A 负载',55+85*((v-3.3)*.15+v*50e-6))],
                      '输入电压 / V','结温 / °C',horizontal=[(110,'设计结温上限')])
    if key == 'ratio':
        rho=np.linspace(-1,1,201)
        return curves(rho,[('一阶分压误差',.5*np.sqrt(2*(1-rho)))],
                      '两电阻相对误差的相关系数','输出相对标准差 / %')
    if key == 'envelope':
        v=np.linspace(12,36,161)
        return curves(v,[(f'电感 {l} µH',5*(1-5/v)/(l*1e-6*250e3)) for l in (16,20,24)],
                      '输入电压 / V','电感电流峰峰值 / A')
    if key == 'zero':
        n=np.geomspace(100,200000,251)
        return curves(n,[('零次失败的 95% 单侧上界',-1e6*np.expm1(np.log(.05)/n))],
                      '独立有效样本数','失效概率上界 / ppm', log=True)
    if key == 'recover':
        return curves([0,1,1.1,1.4,1.8,2.2,2.6,3,3.5,4],
                      [('反馈路负载端口',[12,12,11.5,11.8,11.7,11.75,11.85,12,12.01,12])],
                      '时间 / ms','端口电压 / V',horizontal=[(11.76,'12 V 的 −2% 下限')],
                      vertical=(1.,), dots=True)
    if key == 'probe':
        t=np.linspace(0,20,501)
        return curves(t,[(label,np.where(t<=5,-20*np.expm1(-t/tau),
                        -20*np.expm1(-5/tau)*np.exp(-np.maximum(t-5,0)/tau)))
                         for label,tau in [('时间常数 1 ns',1.),('时间常数 5 ns',5.)]],
                      '相对窄脉冲起点的时间 / ns','探头显示的增量 / V',vertical=(5.,))
    raise KeyError(key)


def example(chapter, title, key, caption, formula, paragraphs):
    return dict(chapter=chapter, title=title, figure=partial(field_plot,key),
                caption=caption, formula=formula, paragraphs=paragraphs)


