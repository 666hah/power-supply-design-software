def lesson(chapter, title, formula, plot, caption, text):
    paragraphs = [line.strip() for line in text.strip().splitlines() if line.strip()]
    if len(paragraphs) != 4:
        raise ValueError(f'{title} 需要四个推导段落')
    return dict(chapter=chapter, title=title, paragraphs=paragraphs,
                formula=formula, figure=plot, caption=caption)


