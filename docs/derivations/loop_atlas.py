def crossing_map():
    fig = figure(height=3.10)
    top, bottom = fig.subplots(2, 1, sharex=True)
    f = np.array([400, 800, 1200, 1800, 2700, 4000])
    db = np.array([6., -2., -1., 3., 1., -3.])
    phase = np.array([-85, -105, -125, -150, -160, -184])
    top.semilogx(f, db, '-o', ms=3, color=BLUE)
    bottom.semilogx(f, phase, '-o', ms=3, color=TEAL)
    top.axhline(0, lw=.8, color=MUTED)
    for i in [0, 2, 4]:
        k = -db[i]/(db[i+1]-db[i])
        fx = f[i]*(f[i+1]/f[i])**k
        for ax in [top, bottom]:
            ax.axvline(fx, ls=':', lw=.9, color=ORANGE)
        bottom.plot(fx, phase[i]+k*(phase[i+1]-phase[i]), 'o', ms=4, color=ORANGE)
    top.set_ylabel('开环幅值 / dB')
    bottom.set(xlabel='扫频频率 / Hz', ylabel='展开相位 / (°)')
    return fig


def rounded_network():
    fig, ax = _axes('频率 / Hz', '选用标称值后的增益差 / dB', log=True)
    s = 2j*pi*np.geomspace(10, 100000, 501)
    goal = 1000/s*(1+s/(2*pi*200))/(1+s/(2*pi*2000))
    r1, r2, c1, c2 = 10000, 9100, 91e-9, 10e-9
    actual = (1+s*r2*c1)/(r1*s*(c1+c2)*(1+s*r2*c1*c2/(c1+c2)))
    ax.plot(np.imag(s)/(2*pi), 20*np.log10(abs(actual/goal)), color=BLUE)
    ax.axhline(0, color=MUTED, lw=.7)
    for f in [200, 2000]:
        ax.axvline(f, color=ORANGE, lw=.8, ls=':')
    return fig


