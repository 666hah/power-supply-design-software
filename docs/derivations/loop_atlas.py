def _axes(xlabel, ylabel, *, log=False):
    """Make one print-sized teaching plot with a light reading grid."""
    fig = figure(height=2.65)
    ax = fig.subplots()
    if log:
        ax.set_xscale('log')
    ax.set(xlabel=xlabel, ylabel=ylabel)
    ax.grid(True, alpha=.17)
    return fig, ax


def buck_damping():
    fig, ax = _axes('扰动频率 / kHz', '相对直流增益 / dB', log=True)
    f0 = 1 / (2*pi*np.sqrt(10e-6*100e-6))
    f = np.geomspace(300, 55000, 560)
    for r, color in [(0.5, ORANGE), (2., BLUE)]:
        q = r*np.sqrt(100e-6/10e-6)
        den = 1-(f/f0)**2+1j*f/(q*f0)
        ax.plot(f/1000, -20*np.log10(abs(den)), color=color, label=f'负载 {r:g} Ω')
        ax.plot(f0/1000, 20*np.log10(q), 'o', color=color)
    ax.axvline(f0/1000, color=MUTED, ls=':', lw=1)
    ax.legend()
    return fig


def inverse_step():
    fig, ax = _axes('占空比阶跃后时间 / µs', '输出增量 / mV')
    l, c, q, r, v = 100e-6, 100e-6, .5, 12, 24
    sys = TransferFunction([-(v/q)*l/(q*q*r), v/q], [l*c/q**2, l/(q*q*r), 1.])
    t, y = step(sys, T=np.linspace(0, 120e-6, 480))
    ax.plot(t*1e6, 1000*.01*y, color=BLUE, label='两状态平均解')
    mask = t <= 38e-6
    ax.plot(t[mask]*1e6, -4*.01/c*t[mask]*1e3, color=ORANGE, ls='--', label='初始切线')
    idx = np.argmin(y)
    ax.plot(t[idx]*1e6, 10*y[idx], 'o', color=BLUE)
    ax.axhline(0, color=MUTED, lw=.8)
    ax.legend()
    return fig


