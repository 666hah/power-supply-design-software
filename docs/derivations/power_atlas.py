LESSONS = []


def axis(start, stop, points=241):
    return np.linspace(start, stop, points)


def _draw(x, traces, xlabel, ylabel, kind, marker):
    fig = figure(7.0, 2.68)
    ax = fig.subplots()
    for i, (name, y) in enumerate(traces):
        style = dict(color=(BLUE, ORANGE, TEAL)[i % 3], label=name)
        if kind == "bar":
            width = .72 / len(traces)
            pos = np.arange(len(x)) + (i - (len(traces) - 1) / 2) * width
            ax.bar(pos, y, width=width, **style)
            ax.set_xticks(np.arange(len(x)), x)
        else:
            ax.plot(x, y, marker="o" if len(x) < 18 else None, **style)
    if marker is not None:
        ax.axhline(marker, color="#667484", lw=.95, ls="--")
    ax.set(xlabel=xlabel, ylabel=ylabel)
    ax.grid(axis="y", alpha=.2)
    if len(traces) > 1:
        ax.legend(loc="best", ncol=min(3, len(traces)))
    return fig


def chart(x, xlabel, ylabel, *traces, kind="line", marker=None):
    return partial(_draw, x, traces, xlabel, ylabel, kind, marker)


def lesson(chapter, title, formula, caption, graph, text):
    paragraphs = [p.strip() for p in text.strip().split("\n") if p.strip()]
    if len(paragraphs) != 4:
        raise ValueError(title)
    LESSONS.append(dict(chapter=chapter, title=title, formula=formula,
                        caption=caption, figure=graph, paragraphs=paragraphs))


